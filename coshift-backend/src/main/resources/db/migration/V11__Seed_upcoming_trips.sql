--  V11 — Des trajets à venir dans chaque organisation (jeu de démonstration)
-- =============================================================================
--  Depuis V10, la recherche ne montre que les trajets d'une organisation
--  partagée. Le jeu de démonstration ne le supportait pas : sur 152 trajets,
--  119 étaient déjà passés et les 25 encore à venir se répartissaient sur onze
--  organisations. Mesuré avant cette migration : 17 comptes sur 122 ne voyaient
--  aucun trajet à venir, et 40 n'en voyaient qu'un seul. Démontrer le cercle
--  fermé sur un écran vide ne démontre rien.
--
--  Cette migration ajoute 56 trajets à venir. Cinq par organisation, sauf celles qui ne comptent pas assez de conducteurs
--  proprietaires d'un vehicule d'au moins trois places (he-condroz : 4, novaris : 4, sainte-gertrude : 3).
--  Chaque trajet est confié à un conducteur différent au sein de son
--  organisation, tant qu'il en reste.
--
--  LES COUPLES CONDUCTEUR-VÉHICULE NE SONT PAS INVENTÉS
--  Ils ont été lus dans la base : chaque trajet part d'un véhicule qui
--  appartient réellement à son conducteur, et propose au plus une place de
--  moins que le véhicule n'en compte. Ce sont les deux règles que
--  `publishTrip` fait respecter ; un jeu de démonstration qui les enfreindrait
--  décrirait un état que l'application refuse de produire.
--
--  LES DATES SONT RELATIVES À L'EXÉCUTION
--  V3 avait écrit des dates absolues, et c'est précisément ce qui a vidé les
--  recherches : un jeu de démonstration écrit en juin est périmé en août.
--  `DATE_ADD(CURDATE(), INTERVAL n DAY)` rend ces trajets à venir quel que soit
--  le jour où la migration est jouée. Les départs s'échelonnent de J+2 à J+25,
--  à 7h30 ou 17h00 — des horaires de domicile-travail, qui sont le sujet.
--
--  RÉSERVÉ À LA DÉMONSTRATION
--  Comme V3 et V4, cette migration insère des données fictives et tourne sur
--  tous les profils, `prod` compris. C'est une dette connue et assumée du
--  projet, pas un oubli : elle est consignée comme telle.
-- =============================================================================

